-- Preserva os ids e as chaves estrangeiras existentes.
-- BY DEFAULT permite informar id explicitamente; novas inserções podem omiti-lo.
-- Cada sequência é sincronizada com o maior id já existente.
ALTER TABLE ws4.clientes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('ws4.clientes','id'), (SELECT MAX(id) FROM ws4.clientes), true);
ALTER TABLE ws4.pedidos ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('ws4.pedidos','id'), (SELECT MAX(id) FROM ws4.pedidos), true);
